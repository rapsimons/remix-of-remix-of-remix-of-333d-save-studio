import {
  Type,
  Image as ImageIcon,
  Layers,
  Undo2,
  Redo2,
  Trash2,
  Save,
  Share2,
  Download,
  Plus,
  X,
  Check,
  RotateCw,
  Box,
  Sticker,
  FileType,
  FolderOpen,
  Moon,
  Sun,
  Play,
  Pause,
  Lock,
  ArrowUp,
  ArrowDown,
  Copy,
  Crosshair,
  Link as LinkIcon,
  Upload,
  FlipHorizontal,
  type LucideIcon,
} from "lucide-react";

export const icons = {
  text: Type,
  image: ImageIcon,
  layers: Layers,
  undo: Undo2,
  redo: Redo2,
  delete: Trash2,
  save: Save,
  share: Share2,
  download: Download,
  add: Plus,
  close: X,
  check: Check,
  rotate: RotateCw,
  model: Box,
  sticker: Sticker,
  font: FileType,
  designs: FolderOpen,
  moon: Moon,
  sun: Sun,
  play: Play,
  pause: Pause,
  lock: Lock,
  up: ArrowUp,
  down: ArrowDown,
  copy: Copy,
  align: Crosshair,
  link: LinkIcon,
  upload: Upload,
  flip: FlipHorizontal,
} satisfies Record<string, LucideIcon>;

export type IconName = keyof typeof icons;

export function Icon({ name, className = "size-4" }: { name: IconName; className?: string }) {
  const C = icons[name];
  return <C className={className} strokeWidth={1.25} aria-hidden />;
}
