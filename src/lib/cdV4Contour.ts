/** The artwork perimeter and spindle bore, with continuous physical sidewalls. */
export function createSawbladeRimGeometry(thickness = CD_V4_THICKNESS) {
  const positions: number[] = [];
  const normals: number[] = [];
  const uvs: number[] = [];
  const indices: number[] = [];
  const wall = (points: [number, number][], inward: boolean) => {
    const base = positions.length / 3;
    for (let i = 0; i <= points.length; i++) {
      const a = points[i % points.length];
      const prev = points[(i + points.length - 1) % points.length];
      const next = points[(i + 1) % points.length];
      if (!a || !prev || !next) continue;
      const dx = next[0] - prev[0], dy = next[1] - prev[1];
      const len = Math.hypot(dx, dy) || 1;
      const sign = inward ? -1 : 1;
      for (const z of [-thickness / 2, thickness / 2]) {
        positions.push(a[0], a[1], z);
        normals.push(sign * dy / len, -sign * dx / len, 0);
        uvs.push(i / points.length, z > 0 ? 1 : 0);
      }
      if (i < points.length) {
        const v = base + i * 2;
        if (inward) indices.push(v, v + 1, v + 2, v + 1, v + 3, v + 2);
        else indices.push(v, v + 2, v + 1, v + 1, v + 2, v + 3);
      }
    }
  };
  wall(CONTOUR, false);
  wall(Array.from({ length: 128 }, (_, i): [number, number] => {
    const a = i / 128 * Math.PI * 2;
    return [Math.cos(a) * CD_V4_HOLE_RADIUS, Math.sin(a) * CD_V4_HOLE_RADIUS];
  }), true);
  const geometry = new THREE.BufferGeometry();
  geometry.setAttribute("position", new THREE.Float32BufferAttribute(positions, 3));
  geometry.setAttribute("normal", new THREE.Float32BufferAttribute(normals, 3));
  geometry.setAttribute("uv", new THREE.Float32BufferAttribute(uvs, 2));
  geometry.setIndex(indices);
  geometry.computeBoundingSphere();
  return geometry;
}
